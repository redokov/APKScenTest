# -*- coding: utf-8 -*-
# t8 COM read-only probe: units available for "Внесение удобрений" (АпкНормы).
import win32com.client, sys

agent = win32com.client.Dispatch('V85.COMConnector').Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';")
q = ('ВЫБРАТЬ '
     'Хар.Ссылка КАК Ссылка, Хар.Владелец КАК ВидРаботы, '
     'Нормы.МодельТехники КАК МодельТехники, '
     'Нормы.ЕдиницВАгрегате КАК ЕдиницВАгрегате, '
     'Нормы.ДоступныГектары КАК Га, Нормы.ДоступныТонны КАК Т, '
     'Нормы.ДоступныКилометры КАК Км, Нормы.ДоступенДопОбъем КАК Доп, '
     'Нормы.СменнаяНормаВыработки КАК Норма, '
     'Нормы.ЕдиницаИзмеренияСменнойНормыВыработки КАК ЕдНормы '
     'ИЗ Справочник.АпкХарактеристикиВидовРабот.АпкНормы КАК Нормы '
     'ЛЕВОЕ СОЕДИНЕНИЕ Справочник.АпкХарактеристикиВидовРабот КАК Хар '
     'ПО Нормы.Ссылка = Хар.Ссылка '
     'ГДЕ Нормы.Ссылка.Владелец.Наименование = "Внесение удобрений"')
res = agent.NewObject('Query')
res.Text = q
sel = res.Execute().Choose()
out = []
cnt = 0
while sel.Next():
    cnt += 1
    out.append('модель=%s | ед.в.агр=%s | Га=%s Т=%s Км=%s Доп=%s | норма=%s (%s)' % (
        agent.String(sel.МодельТехники), sel.ЕдиницВАгрегате,
        sel.Га, sel.Т, sel.Км, sel.Доп,
        sel.Норма, agent.String(sel.ЕдНормы)))
out.append('ВСЕГО строк норм: %d' % cnt)
sys.stdout.buffer.write(('\n'.join(out)).encode('utf-8'))
