# -*- coding: utf-8 -*-
"""T3 диагностика: СтруктураПредприятия - элементы/группы с именем
СТФ Агидельская (и какой выбрался в probe), владелец ферм у каждого.
Usage: python scripts/s006_diag_struct.py"""
import io
import sys

sys.path.insert(0, "scripts")
import win32com.client
import t8_gate as t

out = io.open("tmp/s006/diag-struct.txt", "w", encoding="utf-8")


def w(s=u""):
    out.write(s + u"\n")


agent = win32com.client.Dispatch("V85.COMConnector").Connect(
    t.conn_str(t.ADMIN, u""))

q = agent.NewObject(u"Запрос")
q.Text = (u"ВЫБРАТЬ Спр.Ссылка КАК R, ПРЕДСТАВЛЕНИЕ(Спр.Ссылка) КАК P, "
           u"ВЫБОР КОГДА Спр.Родитель = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка) "
           u"ТОГДА 0 ИНАЧЕ 1 КОНЕЦ КАК HasParent, "
           u"ПРЕДСТАВЛЕНИЕ(Спр.Родитель) КАК Parent, "
           u"КОЛИЧЕСТВО(Фермы.Ссылка) КАК NFerm "
           u"ИЗ Справочник.СтруктураПредприятия КАК Спр "
           u"ЛЕВОЕ СОЕДИНЕНИЕ Справочник.АпкФермы КАК Фермы "
           u"ПО Фермы.Владелец = Спр.Ссылка "
           u"ГДЕ Спр.Наименование ПОДОБНО \"%Агидельская%\" "
           u"СГРУППИРОВАТЬ ПО Спр.Ссылка, Спр.Родитель")
s = q.Execute().Choose()
w(u"СтруктураПредприятия с 'Агидельская':")
while s.Next():
    w(u"  [%s] | uuid=%s | группа=%s | родитель=[%s] | ферм-владелец=%s"
      % (s.P, s.R.UUID(), s.HasParent, s.Parent, s.NFerm))
w(u"")
# у кого какие фермы в собственности (по всем элементам структуры)
q2 = agent.NewObject(u"Запрос")
q2.Text = (u"ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Фермы.Владелец) КАК Owner, "
           u"ПРЕДСТАВЛЕНИЕ(Фермы.Ссылка) КАК F, "
           u"ВЫБОР КОГДА Фермы.Владелец.Родитель = ЗНАЧЕНИЕ(Справочник.СтруктураПредприятия.ПустаяСсылка) "
           u"ТОГДА 0 ИНАЧЕ 1 КОНЕЦ КАК OwnGrp "
           u"ИЗ Справочник.АпкФермы КАК Фермы")
s2 = q2.Execute().Choose()
w(u"Все фермы и их владельцы:")
while s2.Next():
    w(u"  ферма [%s] | владелец [%s] | владелец-группа=%s"
      % (s2.F, s2.Owner, s2.OwnGrp))
out.close()
print("done")
