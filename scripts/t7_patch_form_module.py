# -*- coding: utf-8 -*-
"""T7: добавить в Module.bsl формы кнопку-обработчик «Сформировать отчёт»
и серверную функцию Сервер_СобратьОтчет (ТЧ ОтчетСценарии + ИтогОтчета).
Idempotent. Файл: UTF-8 BOM, LF.
"""
import sys

PATH = r"c:\MyProjects\APKScenTest\src\АпкПодготовкаСценарныхТестов\Forms\Форма\Ext\Form\Module.bsl"

HANDLER = '''
&НаКлиенте
Процедура СформироватьОтчет(Команда)

	Если ПустаяСтрока(СокрЛП(КаталогПрогона)) Тогда
		ПоказатьПредупреждение(,
			НСтр("ru = 'Укажите каталог прогона с batches.json (после прогона)'"));
		Возврат;
	КонецЕсли;
	Попытка
		ИтогОтчета = Сервер_СобратьОтчет(СокрЛП(КаталогПрогона));
	Исключение
		ИтогОтчета = ПодробноеПредставлениеОшибки(ИнформацияОбОшибке());
	КонецПопытки;

КонецПроцедуры

'''

SERVER_FUNC = '''
&НаСервере
Функция Сервер_СобратьОтчет(КаталогПрогона)

	Обработка = РеквизитФормыВЗначение("Объект");
	Результат = Обработка.СобратьОтчет(КаталогПрогона);

	ТаблицаОтчет = Новый ТаблицаЗначений;
	ТаблицаОтчет.Колонки.Добавить("Сценарий",       Новый ОписаниеТипов("Строка"));
	ТаблицаОтчет.Колонки.Добавить("Пользователь",   Новый ОписаниеТипов("Строка"));
	ТаблицаОтчет.Колонки.Добавить("Статус",         Новый ОписаниеТипов("Строка"));
	ТаблицаОтчет.Колонки.Добавить("ДлительностьМс", Новый ОписаниеТипов("Число"));
	ТаблицаОтчет.Колонки.Добавить("СтатусБатча",    Новый ОписаниеТипов("Строка"));
	ТаблицаОтчет.Колонки.Добавить("КодВозврата",    Новый ОписаниеТипов("Строка"));
	Для Каждого Сценарий Из Результат.Сценарии Цикл
		СтрокаОтчета = ТаблицаОтчет.Добавить();
		СтрокаОтчета.Сценарий       = ЗначениеСвойства(Сценарий, "scenario", "");
		СтрокаОтчета.Пользователь   = ЗначениеСвойства(Сценарий, "user", "");
		СтрокаОтчета.Статус         = ЗначениеСвойства(Сценарий, "status", "");
		СтрокаОтчета.ДлительностьМс = Число(ЗначениеСвойства(Сценарий, "durationMs", 0));
		СтрокаОтчета.СтатусБатча    = ЗначениеСвойства(Сценарий, "batchStatus", "");
		СтрокаОтчета.КодВозврата    = ЗначениеСвойства(Сценарий, "returnStatus", "");
	КонецЦикла;
	ЗначениеВРеквизитФормы(ТаблицаОтчет, "ОтчетСценарии");

	Итоги = Результат.Итоги;
	Возврат "Батчей: " + Итоги.batches
		+ "; сценариев: " + Итоги.scenarios
		+ "; passed: " + Итоги.passed + ", failed: " + Итоги.failed
		+ ", broken: " + Итоги.broken + ", timeout: " + Итоги.timeout
		+ ", unknown: " + Итоги.unknown
		+ Символы.ПС + Результат.ПутьJSON + Символы.ПС + Результат.ПутьMD;

КонецФункции

'''


def main():
    with open(PATH, encoding="utf-8-sig", newline="") as f:
        text = f.read()
    stripped = text.rstrip()
    if "Процедура СформироватьОтчет" in text:
        print("[SKIP] already patched")
        return

    handler_anchor = "#КонецОбласти\n\n#Область ПрогонVA\n"
    assert text.count(handler_anchor) == 1, "handler anchor not found"
    text = text.replace(handler_anchor,
                        HANDLER.rstrip("\n") + "\n\n" + "#КонецОбласти\n\n#Область ПрогонVA\n")

    server_anchor = "#КонецОбласти\n\n#КонецОбласти"
    assert text.count(server_anchor) == 1, "server anchor not found"
    text = text.replace(server_anchor,
                        SERVER_FUNC.rstrip("\n") + "\n\n#КонецОбласти\n\n#КонецОбласти")

    with open(PATH, "w", encoding="utf-8-sig", newline="") as f:
        f.write(text)
    print("[OK] Module.bsl patched, lines:", text.count("\n"))


if __name__ == "__main__":
    sys.exit(main())
