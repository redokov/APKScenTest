"""S009 T2 (s010-fix): COM-верификация АРМ-цепочки после E2E:
- ПБЗ (Документ.ПроизводствоБезЗаказа) за ноябрь 2026 созданы (от Выпуска услуг);
- ТЧ ВыходныеИзделия ПБЗ не пуста (риск root-cause tmp/t9: пустая ТЧ -> нет
  ПартииПроизводства -> АРМ выработки silent no-op);
- ВыработкаСотрудников (Документ.ВыработкаСотрудников) за ноябрь > 0;
- партия производства с документом = ПБЗ (Код="1") - опционально.

s010-багфикс: прежний q_all делал rows.append(sel) - sel один объект
выборки, после цикла все элементы показывали ПОСЛЕДНЮЮ запись
(5 строк 'НВЦБ-000007'). Теперь значения копируются в dict внутри цикла.
"""
import sys
import io

sys.path.insert(0, 'scripts')
import win32com.client
import t8_gate as t

sys.stdout.reconfigure(encoding='utf-8', errors='replace')
conn = win32com.client.Dispatch("V85.COMConnector").Connect(t.conn_str(t.ADMIN, ""))

out = io.open('tmp/s009/com_check.txt', 'w', encoding='utf-8')


def q_all(txt, fields):
    """Выполнить запрос; вернуть list[dict] с копиями значений полей."""
    qq = conn.NewObject("Query")
    qq.Text = txt
    sel = qq.Execute().Choose()
    rows = []
    while sel.Next():
        rows.append({f: getattr(sel, f) for f in fields})
    return rows


# 1. ПБЗ за ноябрь
rows = q_all(
    "ВЫБРАТЬ Док.Ссылка КАК Реф, Док.Номер КАК Номер, Док.Дата КАК Дата, "
    "Док.Проведен КАК Проведен ИЗ Документ.ПроизводствоБезЗаказа КАК Док "
    "ГДЕ Док.Дата МЕЖДУ ДАТАВРЕМЯ(2026, 11, 1) И ДАТАВРЕМЯ(2026, 11, 30, 23, 59, 59)",
    ["Реф", "Номер", "Дата", "Проведен"])
out.write("PBZ November: %d\n" % len(rows))
for r in rows:
    vi = r["Реф"].ВыходныеИзделия
    out.write("  %s date=%s posted=%s VI_rows=%d\n" % (
        r["Номер"], r["Дата"], r["Проведен"], vi.Count()))

# 2. Выработка сотрудников за ноябрь
rows = q_all(
    "ВЫБРАТЬ Док.Ссылка КАК Реф, Док.Номер КАК Номер, Док.Проведен КАК Проведен "
    "ИЗ Документ.ВыработкаСотрудников КАК Док "
    "ГДЕ Док.Дата МЕЖДУ ДАТАВРЕМЯ(2026, 11, 1) И ДАТАВРЕМЯ(2026, 11, 30, 23, 59, 59)",
    ["Реф", "Номер", "Проведен"])
out.write("Vyrabotka November: %d\n" % len(rows))
for r in rows:
    out.write("  %s posted=%s\n" % (r["Номер"], r["Проведен"]))

# 3. ПартииПроизводства с документом-основанием ПБЗ ноября
# (s011: без отбора по дате ПЕРВЫЕ 10 ловили посторонние НВ00-партии)
rows = q_all(
    "ВЫБРАТЬ Партия.Ссылка КАК Реф, Партия.Код КАК Код, "
    "Партия.Документ.Номер КАК ДокНомер, Партия.Документ.Проведен КАК ДокПроведен "
    "ИЗ Справочник.ПартииПроизводства КАК Партия "
    "ГДЕ Партия.Документ ЕСТЬ НЕ NULL "
    "И Партия.Документ ССЫЛКА Документ.ПроизводствоБезЗаказа "
    "И Партия.Документ.Дата МЕЖДУ ДАТАВРЕМЯ(2026, 11, 1) И ДАТАВРЕМЯ(2026, 11, 30, 23, 59, 59)",
    ["Реф", "Код", "ДокНомер", "ДокПроведен"])
out.write("PartiiProizvodstva (PBZ November): %d\n" % len(rows))
for r in rows:
    out.write("  code=%s doc=%s posted=%s\n" % (r["Код"], r["ДокНомер"], r["ДокПроведен"]))

out.close()
print(io.open('tmp/s009/com_check.txt', encoding='utf-8').read())
