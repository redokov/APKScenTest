# -*- coding: utf-8 -*-
# t8-finish-7: F4-шаблон - добавить ввод ДатаНачалаРабот + NB про дату/период.
import io

SRC = r"c:\MyProjects\APKScenTest\tests\templates\01-pl-tractor.feature"

old = io.open(SRC, encoding="utf-8", newline="").read()

# --- 1. Комментарий про плейсхолдер {{date}} ---
old_c = "# Плейсхолдеры: {{user}} - имя пользователя ИБ; {{date}} - дата текущим месяцем;"
new_c = "# Плейсхолдеры: {{user}} - имя пользователя ИБ; {{date}} - дата документа-представителя"
assert old.count(old_c) == 1
old = old.replace(old_c, new_c)

# --- 2. NB про дату/период действия объектов затрат ---
old_nb = "# NB (T8): поля \"МоточасовПриВыезде\"/\"МоточасовПриВозвращении\" НЕ вводим:"
new_nb = """# NB (T8): {{date}} = дата документа-представителя (НЕ дата сеанса) и шаг
# ввода ДатаНачалаРабот обязателен после Даты: ДеньРаботы строк ТЧ = Объект.ДатаНачалаРабот,
# а выбор объектов затрат (АналитикаРасходов) фильтруется по АпкНаДату=ДеньРаботы -
# у объектов затрат есть период действия (РегистрСведений.АпкИсторияПолей_ДанныеДляПодбора),
# у документов прошлых лет он истек, и при текущей дате объект не выбрать (probe6).
# NB (T8): поля "МоточасовПриВыезде"/"МоточасовПриВозвращении" НЕ вводим:"""
assert old.count(old_nb) == 1
old = old.replace(old_nb, new_nb)

# --- 3. Шаг ввода ДатаНачалаРабот после Даты ---
old_step = """	И в поле с именем "Дата" я ввожу текст "{{date}}"
	И я перехожу к следующему реквизиту"""
new_step = """	И в поле с именем "Дата" я ввожу текст "{{date}}"
	И я перехожу к следующему реквизиту
	И в поле с именем "ДатаНачалаРабот" я ввожу текст "{{date}}"
	И я перехожу к следующему реквизиту"""
assert old.count(old_step) == 1
old = old.replace(old_step, new_step)

io.open(SRC, "w", encoding="utf-8", newline="").write(old)
print("template updated")
