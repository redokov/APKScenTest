# -*- coding: utf-8 -*-
"""T8 F1: добавить производное поле фикстуры (<Поле>Список из valueMaps)."""
import io
import sys

P = r"c:\MyProjects\APKScenTest\src\АпкПодготовкаСценарныхТестов\Ext\ObjectModule.bsl"

src = io.open(P, encoding="utf-8").read()

old_loop = ("\t\t\t\t\t\tИмяПоля = СокрЛП(Строка(Поле));\n"
            "\t\t\t\t\t\tДобавитьПолеФикстуры(ДанныеСтроки, ИмяПоля, СтрокаТЧ[ИмяПоля]);")
new_loop = ("\t\t\t\t\t\tИмяПоля = СокрЛП(Строка(Поле));\n"
            "\t\t\t\t\t\tДобавитьПолеФикстуры(ДанныеСтроки, ИмяПоля, СтрокаТЧ[ИмяПоля]);\n"
            "\t\t\t\t\t\tДобавитьПроизводноеПолеФикстуры(ДанныеСтроки, ОпределениеТипа, ИмяПоля, СтрокаТЧ[ИмяПоля]);")
assert src.count(old_loop) == 1, "loop old_text count=%d" % src.count(old_loop)
src = src.replace(old_loop, new_loop)

new_proc = """
// Производное поле фикстуры по карте соответствий значений (valueMaps
// карты покрытия): для поля с картой добавляет ключ <Поле>Список с
// отображённым представлением значения (T8 NB: представление элемента
// СПИСКА ВЫБОРА может отличаться от представления перечисления -
// см. АпкРастениеводствоСервер.СформироватьСписокВыбораТипаЗатрат:
// "Прямые затраты" в списке выбора выглядит как "На прямые затраты").
Процедура ДобавитьПроизводноеПолеФикстуры(Приемник, ОпределениеТипа, ИмяПоля, Значение)

	КартыЗначений = ЗначениеСвойства(ОпределениеТипа, "valueMaps", Неопределено);
	Если ТипЗнч(КартыЗначений) <> Тип("Структура") Тогда
		Возврат;
	КонецЕсли;
	Карта = Неопределено;
	Если Не КартыЗначений.Свойство(ИмяПоля, Карта) Тогда
		Возврат;
	КонецЕсли;
	Если ТипЗнч(Карта) <> Тип("Структура") Тогда
		Возврат;
	КонецЕсли;
	Если Значение = Null Или Значение = Неопределено Тогда
		Возврат;
	КонецЕсли;
	Отображённое = Неопределено;
	Если Карта.Свойство(СокрЛП(Строка(Значение)), Отображённое) Тогда
		Приемник.Вставить(ИмяПоля + "Список", СокрЛП(Строка(Отображённое)));
	КонецЕсли;
КонецПроцедуры
"""

anchor = "\n// Значение поля фикстуры: ссылки - {uuid, presentation},"
assert src.count(anchor) == 1, "anchor count=%d" % src.count(anchor)
idx = src.index(anchor)
src = src[:idx + 1] + new_proc + src[idx + 1:]

io.open(P, "w", encoding="utf-8", newline="").write(src)
print("edited ok")
