# -*- coding: utf-8 -*-
# Правка: АРМ "Выработка сотрудников" — silent no-op fix.
#
# Root cause: PБЗ НВЦБ-000002 (31.10.2026, создан АРМ Выпуск услуг) имеет
# ПУСТУЮ ТЧ ВыходныеИзделия и для него не создана ПартияПроизводства.
# АРМ Выработка требует: Распоряжение=ПБЗ -> АпкПартияПроизводства заполнено
# (Form ЗапуститьОтражение: "не определена соответствующая партия производства"
# -> ЕстьОшибки -> Возврат Неопределено -> ВыполнитьОтражениеАРМ молча выходит).
#
# Правка (обратима):
#  1) В PБЗ НВЦБ-000002 добавить строку ВыходныеИзделия:
#     Номенклатура = "Услуги машино-тракторного парка" (= НоменклатураУслуги
#     вида работы "Загрузка удобрений", Правка #5), Количество = 1,
#     НомерГруппыЗатрат = 1.
#  2) Создать элемент Справочник.ПартииПроизводства:
#     Документ = PБЗ, Код = "1", Номенклатура = "Услуги машино-тракторного парка".
#  3) Восстановить непроведённое состояние PБЗ (до probe-проведения).
#
# Rollback: scripts/t9_rollback_pbz_vyrabotka.py
import io, sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
import win32com.client
conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)'")
out = io.open('tmp/t9/arm-vyusotr-final/upd.log', 'w', encoding='utf-8')
S = conn.String

# --- 1. Найти PБЗ НВЦБ-000002 (окт 2026)
q = conn.NewObject("Query")
q.Text = ("ВЫБРАТЬ Д.Ссылка КАК R ИЗ Документ.ПроизводствоБезЗаказа КАК Д "
          "ГДЕ Д.Номер = \"НВЦБ-000002\" И Д.Дата >= ДАТАВРЕМЯ(2026,10,1)")
sel = q.Execute().Choose()
pbz = None
while sel.Next():
    pbz = sel.R
if pbz is None:
    out.write("PБЗ НЕ НАЙДЕН\n")
    sys.exit(1)
out.write("PBZ=%s\n" % S(pbz))

# --- 2. Номенклатура услуги
nom = conn.Справочники.Номенклатура.НайтиПоНаименованию("Услуги машино-тракторного парка", True)
out.write("nom=%s\n" % S(nom))
if not nom or S(nom) == "":
    out.write("НОМЕНКЛАТУРА НЕ НАЙДЕНА\n")
    sys.exit(1)

# --- 3. Восстановить непроведённое состояние (probe-posting revert)
obj = pbz.ПолучитьОбъект()
if obj.Проведен:
    obj.Записать(conn.РежимЗаписиДокумента.ОтменаПроведения)
    out.write("revert posting: done\n")
else:
    out.write("revert posting: was already unposted\n")

# --- 4. Добавить строку ВыходныеИзделия
have = obj.ВыходныеИзделия.Количество()
out.write("ВыходныеИзделия before=%s\n" % have)
row = obj.ВыходныеИзделия.Добавить()
row.Номенклатура = nom
row.Количество = 1
row.НомерГруппыЗатрат = 1
obj.Записать(conn.РежимЗаписиДокумента.Запись)
out.write("ВыходныеИзделия row added\n")

# --- 5. Создать ПартияПроизводства
# не создаём дубликат
q2 = conn.NewObject("Query")
q2.Text = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК C ИЗ Справочник.ПартииПроизводства КАК П "
           "ГДЕ П.Документ = &D И НЕ П.ПометкаУдаления")
q2.УстановитьПараметр("D", pbz)
sel = q2.Execute().Choose()
sel.Next()
out.write("existing parties=%s\n" % S(sel.C))

party = conn.Справочники.ПартииПроизводства.СоздатьЭлемент()
party.Код = "1"
party.Наименование = "Производство без заказа (НВЦБ-2.2, 31.10.2026); Группа затрат: Услуги машино-тракторного парка"
party.Документ = pbz
party.Номенклатура = nom
party.Записать()
out.write("party ref=%s\n" % S(party.Ссылка))
out.write("uuid=%s\n" % S(party.Ссылка.УникальныйИдентификатор()))
out.write("OK: правка применена\n")
out.close()
print("done")
