# для вида работы "Загрузка удобрений" заполнить поля:
#   НоменклатураРаботы, ЕдиницаВыпускаРабот  <- донор "Внесение удобрений"
#   СтатьяРасходов_ОПР                       <- донор "Уборка территории"
# Rollback: scripts/s2_rollback_upd_nastr_udobren.py (значения были пустые)
import io, sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
import win32com.client
conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)'")
out = io.open('tmp/t8/upd5.log', 'w', encoding='utf-8')

SPRAV = conn.Справочники
VIDY = SPRAV.ВидыРаботСотрудников
dst = getattr(VIDY, "НайтиПоНаименованию")("Загрузка удобрений", True)
d_nom = getattr(VIDY, "НайтиПоНаименованию")("Внесение удобрений", True)
d_opr = getattr(VIDY, "НайтиПоНаименованию")("Уборка территории", True)
out.write("dst=%s\ndon_nom=%s\ndon_opr=%s\n" % (dst, d_nom, d_opr))

EMPTY_ORG = SPRAV.Организации.ПустаяСсылка()
RS = conn.РегистрыСведений.АпкПараметрыОтраженияЗатратРастениеводства

def read_record(ref):
    q = conn.NewObject("Query")
    q.Text = ("ВЫБРАТЬ ПараметрыОтраженияЗатрат.Период КАК П, "
              "ПараметрыОтраженияЗатрат.НоменклатураРаботы КАК НомР, "
              "ПараметрыОтраженияЗатрат.ЕдиницаВыпускаРабот КАК ЕдР, "
              "ПараметрыОтраженияЗатрат.СтатьяРасходов_ОПР КАК СтОПР "
              "ИЗ РегистрСведений.АпкПараметрыОтраженияЗатратРастениеводства КАК ПараметрыОтраженияЗатрат "
              "ГДЕ ПараметрыОтраженияЗатрат.ОбъектНастройки = &Настр "
              "УПОРЯДОЧИТЬ ПО ПараметрыОтраженияЗатрат.Период УБЫВ")
    q.УстановитьПараметр("Настр", ref)
    sel = q.Execute().Choose()
    if not sel.Next():
        return None
    return sel

rd = read_record(dst)
rn = read_record(d_nom)
ro = read_record(d_opr)
if rd is None or rn is None or ro is None:
    out.write("MISSING RECORD rd=%s rn=%s ro=%s\n" % (rd is None, rn is None, ro is None))
    out.close()
    sys.exit(1)

out.write("dst период=%s ном=%s ед=%s ст=%s\n" % (rd.П, rd.НомР, rd.ЕдР, rd.СтОПР))
out.write("don_nom ном=%s ед=%s\n" % (rn.НомР, rn.ЕдР))
out.write("don_opr ст=%s\n" % (ro.СтОПР,))

# все записи dst (ожидаем 1)
q = conn.NewObject("Query")
q.Text = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК N ИЗ РегистрСведений.АпкПараметрыОтраженияЗатратРастениеводства "
          "КАК ПараметрыОтраженияЗатрат ГДЕ ПараметрыОтраженияЗатрат.ОбъектНастройки = &Настр")
q.УстановитьПараметр("Настр", dst)
sel = q.Execute().Choose()
sel.Next()
if sel.N != 1:
    out.write("UNEXPECTED dst records=%s\n" % sel.N)
    out.close()
    sys.exit(1)

# обновление набором записей
Nab = RS.СоздатьНаборЗаписей()
Otb = getattr(Nab, "Отбор")
Otb.Период.Установить(rd.П)
Otb.ОбъектНастройки.Установить(dst)
Otb.Организация.Установить(EMPTY_ORG)
Zap = getattr(Nab, "Добавить")()
Zap.Период = rd.П
Zap.ОбъектНастройки = dst
Zap.Организация = EMPTY_ORG
# копия ресурсов: читаем полные значения dst и заменяем 3 поля
qf = conn.NewObject("Query")
FLDS = ["НоменклатураРаботы", "ХарактеристикаРаботы", "НоменклатураРаботыНаСторону",
        "ХарактеристикаРаботыНаСторону", "ЕдиницаВыпускаРабот", "ЕдиницаВыпускаРаботНаСторону",
        "СтатьяРасходов_ОПР", "СтатьяРасходов_ОХР", "СтатьяРасходов_КР", "СтатьяРасходов_ОЭ",
        "СтатьяРасходов_ОС", "СтатьяРасходов_НМА", "СтатьяРасходов_ТЗР", "СтатьяРасходов_РБП",
        "СтатьяРасходов_СП", "СтатьяРасходов_РЕМ", "СтатьяКалькуляции",
        "ЗатратыЧерезВспомогательноеПроизводствоРУЧ", "ЗатратыЧерезВспомогательноеПроизводствоПЛТ",
        "ЗатратыЧерезВспомогательноеПроизводствоПЛА", "НоменклатураВыпускаНаКапитализациюОбъектов",
        "СтатьяКапитализацииОбъектовЗатрат", "НоменклатураЗатратНаПосев",
        "СтатьяСписанияДооценкиПереводаНаОткормПослеВыбраковки", "СтатьяРасходов_ГибельПосевов",
        "СтатьяРасходов_ВыбытиеПоля", "НоменклатураПрочихЗатратНЗП",
        "СтатьяРасходов_ПереносНЗП_НаОплатуТруда", "СтатьяРасходов_ПрочиеЗатратыНЗП",
        "НоменклатураНЗП_НаОплатуТруда"]
qf.Text = ("ВЫБРАТЬ " + ", ".join(
    ["ПараметрыОтраженияЗатрат.%s КАК F%s" % (r, i) for i, r in enumerate(FLDS)]) +
    " ИЗ РегистрСведений.АпкПараметрыОтраженияЗатратРастениеводства КАК ПараметрыОтраженияЗатрат "
    "ГДЕ ПараметрыОтраженияЗатрат.ОбъектНастройки = &Настр "
    "И ПараметрыОтраженияЗатрат.Период = &Пер И ПараметрыОтраженияЗатрат.Организация = &Орг")
qf.УстановитьПараметр("Настр", dst)
qf.УстановитьПараметр("Пер", rd.П)
qf.УстановитьПараметр("Орг", EMPTY_ORG)
self2 = qf.Execute().Choose()
if not self2.Next():
    out.write("NO FULL RECORD\n")
    out.close()
    sys.exit(1)
for i, r in enumerate(FLDS):
    setattr(Zap, r, getattr(self2, "F%s" % i))
# правка #5: 3 поля
Zap.НоменклатураРаботы = rn.НомР
Zap.ЕдиницаВыпускаРабот = rn.ЕдР
Zap.СтатьяРасходов_ОПР = ro.СтОПР
getattr(Nab, "Записать")(True)
out.write("OK: правка #5 применена\n")
out.close()
print('done')
