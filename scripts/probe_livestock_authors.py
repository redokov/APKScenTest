# -*- coding: utf-8 -*-
"""Разведка животноводства, шаг 2: авторы документов (реальные авторы =
основа сценарной модели). Вывод — UTF-8 в tmp/livestock_authors.txt.
Usage: python scripts/probe_livestock_authors.py"""
import io
import os
import sys

sys.path.insert(0, "scripts")
import win32com.client
import t8_gate as t

OUT = "tmp/livestock_authors.txt"
out = io.open(OUT, "w", encoding="utf-8")


def w(line=u""):
    out.write(line + u"\n")


DOCS = [
    u"АпкГрупповоеПоступлениеЖивотных", u"АпкГрупповоеПеремещениеЖивотных",
    u"АпкГрупповаяПродажаЖивотных", u"АпкГрупповоеВзвешиваниеЖивотных",
    u"АпкГрупповоеЛечениеЖивотных", u"АпкГрупповоеОсеменение",
    u"АпкГрупповойОпорос", u"АпкГрупповойОтъем", u"АпкГрупповойПадежЗабой",
    u"АпкГрупповойПереводВОсновноеСтадо", u"АпкГрупповойПереводМолодняка",
    u"АпкГрупповойУчетныйЛистДвиженияЖивотных",
    u"АпкЖурналНадояМолока", u"АпкВнутреннийРасходМолока", u"АпкКРСТТНМолоко",
    u"АпкКРСГрупповоеПоступлениеЖивотных", u"АпкКРСГрупповойПеревод",
    u"АпкКРСГрупповойУчетныйЛистДвиженияЖивотных",
    u"АпкКРСГрупповоеВзвешиваниеЖивотных", u"АпкКРСГрупповойОтел",
    u"АпкЗамерыШпика", u"АпкРазбирковкаНомерныхПоросят",
]

agent = win32com.client.Dispatch("V85.COMConnector").Connect(
    t.conn_str(t.ADMIN, u""))

w(u"=== АВТОРЫ ДОКУМЕНТОВ ЖИВОТНОВОДСТВА (представление + привязка к ИБ-пользователю) ===")
for name in DOCS:
    try:
        q = agent.NewObject(u"Запрос")
        q.Text = (u"ВЫБРАТЬ РАЗЛИЧНЫЕ ПРЕДСТАВЛЕНИЕ(Документ." + name +
                  u".Автор) КАК АвторИмя, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Документ." +
                  name + u".Ссылка) КАК N ИЗ Документ." + name +
                  u" СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Документ." + name + u".Автор)")
        sel = q.Execute().Choose()
        rows = []
        while sel.Next():
            rows.append(u"%s (%s)" % (sel.АвторИмя, sel.N))
        w(u"[%s] авторы: %s" % (name, u"; ".join(rows) if rows else u"—"))
    except Exception as e:
        w(u"[%s] ОШИБКА: %s" % (name, e))

# Привязка авторов к пользователям ИБ (как в растениеводстве: sourceAuthor
# → ИБ-пользователь): для каждого пользователя справочника Пользователи —
# есть ли ИБ-пользователь с тем же именем
w(u"")
w(u"=== Справочник Пользователи: наименование + ИБ-пользователь ===")
try:
    q = agent.NewObject(u"Запрос")
    q.Text = (u"ВЫБРАТЬ Пользователи.Ссылка КАК Ref ИЗ Справочник.Пользователи")
    sel = q.Execute().Choose()
    while sel.Next():
        ref = sel.Ref
        try:
            ibu = ref.ПользовательИБ  # может не быть реквизита — обернуто
        except Exception:
            ibu = None
        w(u"%s | ИБ: %s" % (ref, ibu if ibu is not None else u"?"))
except Exception as e:
    w(u"ОШИБКА перечисления пользователей: %s" % e)

out.close()
print("authors probe done ->", OUT)
