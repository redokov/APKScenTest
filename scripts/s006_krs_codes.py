# -*- coding: utf-8 -*-
# T4: коды КРС-статусов (Справочник.АпкСтатусыЖивотных), ВидРасхода
# (ВнутреннийРасходМолока), Номенклатура «Молоко», Доярка (ФизЛица).
import io, sys
sys.path.insert(0, 'scripts')
import win32com.client, t8_gate as t

agent = win32com.client.Dispatch('V85.COMConnector').Connect(t.conn_str(t.ADMIN, u''))
out = io.open('tmp/s006/krs-codes.txt', 'w', encoding='utf-8')
q = agent.NewObject(u'Запрос')

def dump(title, text):
    q.Text = text
    s = q.Execute().Choose()
    out.write(u'### %s\n' % title)
    while s.Next():
        out.write(u'[%s] код=%s\n' % (s.N, s.C))

dump(u'КРС-статусы (АпкСтатусыЖивотных), выборка',
u'ВЫБРАТЬ ПЕРВЫЕ 300 Спр.Наименование КАК N, Спр.Код КАК C ИЗ Справочник.АпкСтатусыЖивотных КАК Спр')
dump(u'Виды расхода молока (перечисление/справочник?)',
u'ВЫБРАТЬ ПЕРВЫЕ 20 Спр.Наименование КАК N, Спр.Код КАК C ИЗ Справочник.АпкВидыРасходаМолока КАК Спр')
dump(u'Номенклатура Молоко',
u'ВЫБРАТЬ ПЕРВЫЕ 10 Спр.Наименование КАК N, Спр.Код КАК C ИЗ Справочник.Номенклатура КАК Спр ГДЕ Спр.Наименование ПОДОБНО "%Молоко%"')
dump(u'Доярка Авдеева',
u'ВЫБРАТЬ ПЕРВЫЕ 10 Спр.Наименование КАК N, Спр.Код КАК C ИЗ Справочник.ФизическиеЛица КАК Спр ГДЕ Спр.Наименование ПОДОБНО "%Авдеева%"')
out.close()
print('done')
