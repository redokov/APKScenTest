# -*- coding: utf-8 -*-
# Правка #4 (обратима): настройка РС АпкПараметрыОтраженияЗатратРастениеводства
# для вида работы "Загрузка удобрений" — копия полей с "Загрузка посадочного
# материала (зерновые)". Rollback: scripts/s2_del_nastr_udobren.py
import io, sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
import win32com.client
conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)'")

RES = ["НоменклатураРаботы", "ХарактеристикаРаботы", "НоменклатураРаботыНаСторону",
       "ХарактеристикаРаботыНаСторону", "ЕдиницаВыпускаРабот", "ЕдиницаВыпускаРаботНаСторону",
       "СтатьяРасходов_ОПР", "СтатьяРасходов_ОХР", "СтатьяРасходов_КР", "СтатьяРасходов_ОЭ",
       "СтатьяРасходов_ОС", "СтатьяРасходов_НМА", "СтатьяРасходов_ТЗР", "СтатьяРасходов_РБП",
       "СтатьяРасходов_СП", "СтатьяРасходов_РЕМ", "СтатьяКалькуляции",
       "ЗатратыЧерезВспомогательноеПроизводствоРУЧ", "ЗатратыЧерезВспомогательноеПроизводствоПЛТ",
       "ЗатратыЧерезВспомогательноеПроизводствоПЛА", "НоменклатураВыпускаНаКапитализациюОбъектов",
       "СтатьяКапитализацииОбъектовЗатрат", "НоменклатураЗатратНаПосев",
       "СтатьяСписанияДооценкиПереводаНаОткормПослеВыбраковки", "СтатьяРасходов_ГибельПосевов",
       "СтатьяРасходов_ВыбытиеПоля", "НоменклатураПрочихЗатратНЗП",
       "СтатьяРасходов_ПереносНЗП_НаОплатуТруда", "СтатьяРасходов_ПрочиеЗатратыНЗП",
       "НоменклатураНЗП_НаОплатуТруда"]

SPRAV = conn.Справочники
VIDY = SPRAV.ВидыРаботСотрудников
src = getattr(VIDY, "НайтиПоНаименованию")("Загрузка посадочного материала (зерновые)", True)
dst = getattr(VIDY, "НайтиПоНаименованию")("Загрузка удобрений", True)
print("src:", src)
print("dst:", dst)
if getattr(src, "Пустая")() or getattr(dst, "Пустая")():
    print("NOT FOUND"); sys.exit(1)

# период последней настройки src
q = conn.NewObject("Query")
q.Text = ("ВЫБРАТЬ ПараметрыОтраженияЗатрат.Период КАК П "
          "ИЗ РегистрСведений.АпкПараметрыОтраженияЗатратРастениеводства КАК ПараметрыОтраженияЗатрат "
          "ГДЕ ПараметрыОтраженияЗатрат.ОбъектНастройки = &Настр "
          "УПОРЯДОЧИТЬ ПО ПараметрыОтраженияЗатрат.Период УБЫВ")
q.УстановитьПараметр("Настр", src)
sel = q.Execute().Choose()
if not sel.Next():
    print("NO SRC RECORD"); sys.exit(1)
src_period = sel.П
print("src period:", src_period)

# значения ресурсов src
q2 = conn.NewObject("Query")
q2.Text = ("ВЫБРАТЬ " + ", ".join(
    ["ПараметрыОтраженияЗатрат.%s КАК F%s" % (r, i) for i, r in enumerate(RES)]) +
    " ИЗ РегистрСведений.АпкПараметрыОтраженияЗатратРастениеводства КАК ПараметрыОтраженияЗатрат "
    "ГДЕ ПараметрыОтраженияЗатрат.ОбъектНастройки = &Настр "
    "И ПараметрыОтраженияЗатрат.Период = &Пер")
q2.УстановитьПараметр("Настр", src)
q2.УстановитьПараметр("Пер", src_period)
sel2 = q2.Execute().Choose()
if not sel2.Next():
    print("NO SRC VALUES"); sys.exit(1)

backup = {}
out = io.open('tmp/s2/nastr-backup.txt', 'w', encoding='utf-8')
for i, r in enumerate(RES):
    backup[r] = getattr(sel2, "F%s" % i)
    out.write("%s = %s\n" % (r, backup[r]))
out.close()
print("values read + backup written")

# новая запись набором записей
RS = conn.РегистрыСведений.АпкПараметрыОтраженияЗатратРастениеводства
Nab = RS.СоздатьНаборЗаписей()
Otb = getattr(Nab, "Отбор")
Otb.Период.Установить(src_period)
Otb.ОбъектНастройки.Установить(dst)
EMPTY_ORG = SPRAV.Организации.ПустаяСсылка()
Otb.Организация.Установить(EMPTY_ORG)
Zap = getattr(Nab, "Добавить")()
Zap.Период = src_period
Zap.ОбъектНастройки = dst
Zap.Организация = EMPTY_ORG
for r in RES:
    setattr(Zap, r, backup[r])
getattr(Nab, "Записать")(True)
print("OK: настройка создана")
