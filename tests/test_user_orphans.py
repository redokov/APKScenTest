# Явно тестовые записи — должны определяться как сироты
TEST_USERS = [
    "АпкСценТест_Менеджер", "АпкСценТест_Негатив1", "АпкСценТест_Зонд1",
    "Зонд T8-1 (удаляется)", "Зонд T8-2 (удаляется)",
    "Негатив s004 (удаляется)", "Менеджер раннеров s004 (удаляется)",
    "Менеджер раннеров s004", "Зонд T1",
]

# Крайние случаи — не должны считаться сиротами (безопасность в первую
# очередь: при сомнении НЕ удалять)
EDGE_NOT_ORPHANS = ["", "   ", None, "-", "Нет", "x"]


def test_real_users_never_deleted():
    for name in REAL_USERS:
        assert not is_test_orphan(name), \
            "РЕАЛЬНЫЙ пользователь распознан как сирота: %r" % name
    print("OK: %d реальных пользователей не затрагиваются" % len(REAL_USERS))


def test_test_users_detected():
    for name in TEST_USERS:
        assert is_test_orphan(name), \
            "тестовая запись НЕ распознана как сирота: %r" % name
    print("OK: %d тестовых записей распознаны" % len(TEST_USERS))


def test_edge_cases_safe():
    for name in EDGE_NOT_ORPHANS:
        assert not is_test_orphan(name), \
            "пустая/неясная запись распознана как сирота: %r" % name
    print("OK: %d крайних случаев безопасны" % len(EDGE_NOT_ORPHANS))


def test_full_name_marker():
    # маркер может быть в полном имени, а не в наименовании
    assert is_test_orphan("zTemp004_neg", "Зонд T1 (удаляется)")
    assert not is_test_orphan("ПетровСИ", "Сервис (ГригорьевВА)")
    print("OK: маркер в полном имени работает")


def test_collect_orphans():
    items = [("Агроном", "Агроном"),
             ("АпкСценТест_Менеджер", "Менеджер раннеров s004 (удаляется)"),
             ("Кассир (КазаковаНА)", "Кассир (КазаковаНА)")]
    orphans = collect_orphans(items)
    assert len(orphans) == 1 and orphans[0][0] == "АпкСценТест_Менеджер", \
        "collect_orphans: неверный отбор %r" % orphans
    print("OK: collect_orphans отбирает только сирот")


if __name__ == "__main__":
    test_real_users_never_deleted()
    test_test_users_detected()
    test_edge_cases_safe()
